-- Basic CareBridge tables for a student demo.
-- Run this after enabling Supabase Auth in your project.

CREATE TABLE IF NOT EXISTS public.users (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('elderly', 'family', 'caregiver', 'admin')),
  -- Every non-admin member points to the elderly user's auth ID for their care circle.
  care_circle_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (role = 'admin' OR care_circle_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS public.medicines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  dosage text NOT NULL,
  time time NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, name, time)
);

CREATE TABLE IF NOT EXISTS public.doses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medicine_id bigint NOT NULL REFERENCES public.medicines(id) ON DELETE CASCADE,
  taken boolean NOT NULL DEFAULT false,
  taken_at timestamptz
);

-- These helpers avoid querying the RLS-protected users table from its own policies.
CREATE OR REPLACE FUNCTION public.carebridge_current_role()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT role FROM public.users WHERE id = auth.uid()
$$;

CREATE OR REPLACE FUNCTION public.carebridge_current_circle_id()
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT care_circle_id FROM public.users WHERE id = auth.uid()
$$;

-- RLS still limits which rows authenticated users can read.
GRANT SELECT ON public.users, public.medicines, public.doses TO authenticated;
REVOKE ALL ON FUNCTION public.carebridge_current_role() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.carebridge_current_circle_id() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.carebridge_current_role() TO authenticated;
GRANT EXECUTE ON FUNCTION public.carebridge_current_circle_id() TO authenticated;

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.medicines ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.doses ENABLE ROW LEVEL SECURITY;

-- Members see their own profile and other profiles in the same circle; admins see all.
DROP POLICY IF EXISTS "Users can read their care circle" ON public.users;
CREATE POLICY "Users can read their care circle"
  ON public.users FOR SELECT
  USING (
    id = auth.uid()
    OR public.carebridge_current_role() = 'admin'
    OR care_circle_id = public.carebridge_current_circle_id()
  );

-- Medicines belong to the elderly user at the center of a care circle.
DROP POLICY IF EXISTS "Users can read care circle medicines" ON public.medicines;
CREATE POLICY "Users can read care circle medicines"
  ON public.medicines FOR SELECT
  USING (
    user_id = auth.uid()
    OR user_id = public.carebridge_current_circle_id()
    OR public.carebridge_current_role() = 'admin'
  );

-- A dose is visible when its medicine is visible to the current user.
DROP POLICY IF EXISTS "Users can read care circle doses" ON public.doses;
CREATE POLICY "Users can read care circle doses"
  ON public.doses FOR SELECT
  USING (
    public.carebridge_current_role() = 'admin'
    OR EXISTS (
      SELECT 1
      FROM public.medicines AS medicine
      WHERE medicine.id = doses.medicine_id
        AND (
          medicine.user_id = auth.uid()
          OR medicine.user_id = public.carebridge_current_circle_id()
        )
    )
  );